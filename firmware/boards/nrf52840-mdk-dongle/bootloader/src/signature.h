/*
 * Signed images: the only thing between the drive and running code.
 *
 * Every image carries a 256-byte slot at a fixed address past its end:
 *
 *   0x00  magic    "VKS1"
 *   0x04  kind     SIGNATURE_KIND_APP or SIGNATURE_KIND_BOOTLOADER
 *   0x08  version  the signer's number; carried and signed, not yet compared
 *   0x0C  length   bytes of the image signed, from its first byte
 *   0x10  zero     reserved, signed
 *   0x40  Ed25519 signature (RFC 8032) over slot[0x00..0x40] || image[0..length]
 *   0x80  0xFF     never signed, so it must be erased
 *
 * The public key is compiled in: signing_key.h, generated by build.sh, defines
 * SIGNING_PUBLIC_KEY_BYTES and SIGNING_KEY_FINGERPRINT (shown in INFO_UF2.TXT).
 */

#ifndef SIGNATURE_H_
#define SIGNATURE_H_

#include <stdbool.h>
#include <stdint.h>

#define SIGNATURE_KIND_APP        1
#define SIGNATURE_KIND_BOOTLOADER 2

#define SIGNATURE_SLOT_SIZE       256

/* True only if the slot at `slot` is well formed, of `kind`, signs at most `max_length`
 * bytes from `image` - exactly `max_length` when `exact` - and the signature verifies
 * under the compiled-in key. Feeds the watchdog while it hashes. */
bool signature_valid(uint8_t const *image, uint8_t const *slot, uint32_t kind,
                     uint32_t max_length, bool exact);

#endif /* SIGNATURE_H_ */
