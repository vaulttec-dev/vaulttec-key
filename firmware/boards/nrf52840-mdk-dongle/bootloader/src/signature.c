/*
 * The signature check, built from Monocypher's own crypto_ed25519_check: the same
 * SHA-512 over R || A || message, reduced and checked with crypto_eddsa_check_equation
 * (which also rejects s >= L). Only the message is fed in pieces - the slot header,
 * then the image from flash - because the two are not one buffer.
 */

#include <stddef.h>
#include <stdint.h>

#include "monocypher.h"
#include "monocypher-ed25519.h"
#include "signature.h"
#include "signing_key.h"

/* test/verify.c builds this file for qemu-arm, where there is no watchdog. */
#ifndef SIGNATURE_QEMU_TEST
#include "nrf_wdt.h"
#endif

/* signing_key.h, generated by build.sh, holds the key as SIGNING_PUBLIC_KEY_BYTES */
static uint8_t const SIGNING_PUBLIC_KEY[32] = SIGNING_PUBLIC_KEY_BYTES;

#define SLOT_MAGIC      0x31534B56u /* "VKS1", little endian */
#define SLOT_HEADER     0x40
#define SLOT_SIGNATURE  0x40
#define SLOT_TAIL       0x80
#define CHUNK           4096

static uint32_t le32(uint8_t const *p) {
  return (uint32_t) p[0] | (uint32_t) p[1] << 8 | (uint32_t) p[2] << 16 | (uint32_t) p[3] << 24;
}

/* An application may have started the watchdog, and it survives the reset into the
 * bootloader; hashing a large image must not let it fire. */
static void feed_watchdog(void) {
#ifndef SIGNATURE_QEMU_TEST
  if (nrf_wdt_started(NRF_WDT)) {
    for (uint8_t i = 0; i < 8; i++) nrf_wdt_reload_request_set(NRF_WDT, (nrf_wdt_rr_register_t) i);
  }
#endif
}

bool signature_valid(uint8_t const *image, uint8_t const *slot, uint32_t kind,
                     uint32_t max_length, bool exact) {
  uint32_t const length = le32(slot + 0x0C);

  if (le32(slot) != SLOT_MAGIC || le32(slot + 0x04) != kind) return false;
  if (length == 0 || length > max_length || (exact && length != max_length)) return false;
  for (uint32_t i = 0x10; i < SLOT_HEADER; i++) {
    if (slot[i] != 0) return false;
  }
  for (uint32_t i = SLOT_TAIL; i < SIGNATURE_SLOT_SIZE; i++) {
    if (slot[i] != 0xFF) return false;
  }

  uint8_t const *signature = slot + SLOT_SIGNATURE;
  crypto_sha512_ctx ctx;
  uint8_t hash[64];
  uint8_t h_ram[32];

  crypto_sha512_init(&ctx);
  crypto_sha512_update(&ctx, signature, 32);          /* R */
  crypto_sha512_update(&ctx, SIGNING_PUBLIC_KEY, 32); /* A */
  crypto_sha512_update(&ctx, slot, SLOT_HEADER);
  for (uint32_t done = 0; done < length; done += CHUNK) {
    feed_watchdog();
    uint32_t const n = (length - done < CHUNK) ? length - done : CHUNK;
    crypto_sha512_update(&ctx, image + done, n);
  }
  crypto_sha512_final(&ctx, hash);
  crypto_eddsa_reduce(h_ram, hash);

  return crypto_eddsa_check_equation(signature, SIGNING_PUBLIC_KEY, h_ram) == 0;
}
